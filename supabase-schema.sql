-- Rəfiqə Portfolio starter schema
-- Supabase SQL Editor-də layihə sahibi kimi icra edin.

create extension if not exists pgcrypto;

create table if not exists public.portfolio_links (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 100),
  url text not null check (url ~ '^https?://'),
  is_public boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.portfolio_files (
  id uuid primary key default gen_random_uuid(),
  file_name text not null,
  storage_path text not null unique,
  category text not null check (category in ('cv','document')),
  is_public boolean not null default true,
  uploaded_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.portfolio_events (
  id bigint generated by default as identity primary key,
  event_name text not null check (event_name in ('page_view','project_click','quick_link_click')),
  event_detail text not null default '',
  created_at timestamptz not null default now()
);

alter table public.portfolio_links enable row level security;
alter table public.portfolio_files enable row level security;
alter table public.portfolio_events enable row level security;

-- Public users can read only public links and files.
drop policy if exists "Public can read public links" on public.portfolio_links;
create policy "Public can read public links" on public.portfolio_links
for select to anon, authenticated using (is_public = true);

drop policy if exists "Authenticated users manage links" on public.portfolio_links;
create policy "Authenticated users manage links" on public.portfolio_links
for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);

drop policy if exists "Public can read public files" on public.portfolio_files;
create policy "Public can read public files" on public.portfolio_files
for select to anon, authenticated using (is_public = true);

drop policy if exists "Authenticated users manage files" on public.portfolio_files;
create policy "Authenticated users manage files" on public.portfolio_files
for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);

-- Public visitors may send simple analytics events. Authenticated admins may read.
drop policy if exists "Anyone can record portfolio events" on public.portfolio_events;
create policy "Anyone can record portfolio events" on public.portfolio_events
for insert to anon, authenticated with check (
  event_name in ('page_view','project_click','quick_link_click')
  and char_length(event_detail) <= 160
);

drop policy if exists "Authenticated users can read portfolio events" on public.portfolio_events;
create policy "Authenticated users can read portfolio events" on public.portfolio_events
for select to authenticated using (auth.uid() is not null);

-- Storage: create a PUBLIC bucket named portfolio-files in the dashboard.
-- Policies below allow authenticated users to upload/delete/manage objects in that bucket.
drop policy if exists "Authenticated users upload portfolio files" on storage.objects;
create policy "Authenticated users upload portfolio files" on storage.objects
for insert to authenticated with check (bucket_id = 'portfolio-files');

drop policy if exists "Anyone can read portfolio files" on storage.objects;
create policy "Anyone can read portfolio files" on storage.objects
for select to anon, authenticated using (bucket_id = 'portfolio-files');

drop policy if exists "Authenticated users update portfolio files" on storage.objects;
create policy "Authenticated users update portfolio files" on storage.objects
for update to authenticated using (bucket_id = 'portfolio-files') with check (bucket_id = 'portfolio-files');

drop policy if exists "Authenticated users delete portfolio files" on storage.objects;
create policy "Authenticated users delete portfolio files" on storage.objects
for delete to authenticated using (bucket_id = 'portfolio-files');
